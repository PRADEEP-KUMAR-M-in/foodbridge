"""Builds reports/TEST_REPORT.md from real runs:  python make_test_report.py
Runs the tests, runs the parser check, and quotes the simulation headline. Nothing is typed in by hand except the
mapping from 'what we claim' to the test that checks it (if a test is missing, this script fails loudly)."""
# re = pattern matching (used to pull test names out of pytest output)
import re
# subprocess = lets this script run other commands, like pytest
import subprocess
# sys = access to the running Python and a way to stop with an error message
import sys

# Runs "python <args>" and gives back whatever it printed.
def run_python(*args):
    return subprocess.run([sys.executable, *args], capture_output=True, text=True).stdout

# Run the whole test suite and capture its text output (-rA lists every test, -W ignore hides warnings).
test_output = run_python("-m", "pytest", "-q", "-rA", "-W", "ignore")
# The final "79 passed" style line from the test output.
summary = [line for line in test_output.strip().splitlines() if "passed" in line or "failed" in line][-1]
# Names of the tests that passed.
passed = set(re.findall(r"PASSED [^\n]*?::(test_\w+)", test_output))
# Names of every test that ran (passed OR failed).
names = passed | set(re.findall(r"FAILED [^\n]*?::(test_\w+)", test_output))
# Each row says: "what we claim" and which test(s) back that claim up.
CHECKS = [
    ("Only one organisation can win a claim, even with 8 simultaneous attempts", ["test_concurrent_claims_have_exactly_one_winner"]),
    ("An expired listing cannot be claimed", ["test_expired_listing_cannot_be_claimed"]),
    ("Login required; roles and ownership enforced on every action", ["test_login_required_everywhere", "test_roles_and_ownership_enforced"]),
    ("Pickup code works once, only for the right donor, and acceptance needs it", ["test_pickup_code_is_one_time_donor_bound_and_required_for_acceptance"]),
    ("Unclaimed or failed offers cascade to the next organisation; no-shows cannot re-claim", ["test_offer_goes_to_best_first_then_cascades_then_opens", "test_expired_claim_cascades_and_blocks_reclaim"]),
    ("Editing a recorded event is detected by the audit chain", ["test_impact_reconciles_and_tampering_is_detected"]),
    ("Impact figures are recomputed from recorded events", ["test_impact_detail_is_recomputed_from_events"]),
    ("A reported problem freezes the listing; admin resolves it", ["test_incident_freezes_listing_and_admin_resolves"]),
    ("Fair-share rotation and plain-reason exclusions", ["test_fair_share_band_and_exclusion_reasons"]),
    ("Speak-to-List never guesses storage and always asks for confirmation", ["test_storage_is_never_guessed_and_always_needs_confirmation"]),
    ("Instruction-like text in a listing is treated as data", ["test_nonsense_and_prompt_injection_text_is_just_data"]),
    ("The traceability passport makes no safety claim and is access-limited", ["test_passport_has_record_history_declaration_and_no_safety_claim", "test_passport_and_timeline_access_is_limited_to_involved_orgs"]),
    ("Tamil mode has Tamil text for every English interface string", ["test_tamil_has_a_translation_for_every_english_string"]),
    ("The simulator uses the app's own ranking", ["test_simulated_ranking_matches_the_apps_own_ranking"]),
]
# If a test named above does not exist, collect it so we can stop (no silent gaps in the report).
missing = [test_name for _, test_names in CHECKS for test_name in test_names if test_name not in names]
# Refuse to write a report that points at tests that are not there.
if missing:
    sys.exit(f"Report not written: tests not found: {missing}")
# Turn each claim into a markdown table row, showing "passing" only if ALL its tests passed.
rows = "\n".join(f"| {claim} | {', '.join('`' + test_name + '`' for test_name in test_names)} | {'passing' if all(test_name in passed for test_name in test_names) else 'FAILING'} |" for claim, test_names in CHECKS)
# Run the Speak-to-List accuracy check and keep its output for the report.
parser_report = run_python("check_speak_to_list.py").strip()
# Pull the headline section out of the simulation report (if it exists yet).
try:
    simulation_text = open("reports/SIMULATION_REPORT.md", encoding="utf-8").read()
    simulation_text = simulation_text.split("## What the numbers say")[1].split("##")[0].strip()
# No simulation report yet, so leave a hint about how to make one.
except Exception:
    simulation_text = "(run `python run_simulation.py` first)"
# The whole report text, with the live numbers dropped in.
report_text = f"""# FOODBRIDGE test and evidence report

Generated by `python make_test_report.py`. Test suite result: **{summary}**.

## What the automated tests prove
| Claim | Test | Result |
|---|---|---|
{rows}

## Speak-to-List parser (rules, not AI)
```
{parser_report}
```
These sentences were written by the developers while building the parser, so the figures are optimistic. They must be re-measured on sentences from real donors, especially Tamil.

## Simulation headline (a model, not a measurement)
{simulation_text}

Full tables, sensitivity and assumptions: `reports/SIMULATION_REPORT.md`. The what-if page is `/simulator.html`.

## Not tested (honest list)
- On real phones and real networks (all browser checks were in a simulated browser); QR scanning with a real camera; the microphone with real Tamil speech.
- Load, security review or penetration testing; accessibility audit.
- With real donors or recipients; no pilot has been run. Safe-window hold times are placeholders pending expert review.
- Notification delivery and failure (no external notifications are built); LLM failure (no LLM is used).
"""
# Save the report to disk.
open("reports/TEST_REPORT.md", "w", encoding="utf-8").write(report_text)
# Tell the person what happened.
print("wrote reports/TEST_REPORT.md --", summary)
